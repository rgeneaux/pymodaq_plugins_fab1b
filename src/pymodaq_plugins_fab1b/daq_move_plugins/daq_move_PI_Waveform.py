    def ini_attributes(self):
        super().ini_attributes()
        self._waveform_running = False
        self._servo_dt = None  # s
        self._max_wave_points = None
        self._has_wave_generator = False
        self._syncing = False  # True while the plugin itself rewrites the Speed/Frequency field it computes

    # ---- initialization ---------------------------------------------------------------------------------------
    def ini_stage(self, controller=None):
        info, initialized = super().ini_stage(controller)
        if not initialized:
            return info, initialized
        device = self.controller.device
        axis = self.axis_name
        self._servo_dt = float(device.qSPA(axis, SERVO_UPDATE_TIME_ID)[axis][SERVO_UPDATE_TIME_ID])
        self._max_wave_points = int(device.qSPA(axis, MAX_WAVE_POINTS_ID)[axis][MAX_WAVE_POINTS_ID])
        self._has_wave_generator = device.qTWG() >= 1
        if not self._has_wave_generator:
            self._set_waveform_status('This controller has no wave generator')
        else:
            self._use_position_as_time_zero()  # a safe default: time zero where the stage is
            self._apply_rate_input()
            self._update_plan_info()
        return info, initialized

    # ---- settings ---------------------------------------------------------------------------------------------
    def commit_settings(self, param):
        name = param.name()
        try:
            if name == 'start_waveform':
                if param.value():
                    self.settings.child('waveform', 'start_waveform').setValue(False)
                    self.start_waveform()
            elif name == 'stop_waveform':
                if param.value():
                    self.settings.child('waveform', 'stop_waveform').setValue(False)
                    self.stop_waveform()
            elif name == 'use_position_as_time_zero':
                if param.value():
                    self.settings.child('waveform', 'use_position_as_time_zero').setValue(False)
                    self._use_position_as_time_zero()
                    self._update_plan_info()
            elif name == 'rate_input':
                self._apply_rate_input()
                self._update_plan_info()
            elif name in ('shape', 'time_zero', 'delay_direction', 'delay_min', 'delay_max', 'speed', 'frequency',
                          'corner_smoothing'):
                if not self._syncing:
                    self._update_plan_info()
            else:
                super().commit_settings(param)
        except Exception as exc:
            self._set_waveform_status(f'{name}: {type(exc).__name__}: {exc}')
            self.emit_status(ThreadCommand('Update_Status', [getLineInfo() + str(exc), 'log']))

    def _wf(self, name):
        return self.settings['waveform', name]

    def _set_waveform_status(self, message: str):
        self.settings.child('waveform', 'status').setValue(message)

    def _use_position_as_time_zero(self):
        position = float(self.controller.get_axis_position(self.axis_name))
        self.settings.child('waveform', 'time_zero').setValue(round(position, 3))

    def _increasing(self) -> bool:
        return self._wf('delay_direction') == DIRECTION_UP

    def _delay_span(self) -> float:
        span = self._wf('delay_max') - self._wf('delay_min')
        if span <= 0:
            raise ValueError('Delay max must be greater than delay min')
        return span

    def _position_range(self):
        """Lowest and highest positions (um) of the sweep"""
        return position_range(self._wf('time_zero'), self._wf('delay_min'), self._wf('delay_max'),
                              self._increasing())

    def _requested_frequency(self) -> float:
        """Frequency (Hz) asked for, from the Speed or the Frequency setting, as Rate set by selects"""
        if self._wf('rate_input') == INPUT_SPEED:
            return frequency_from_speed(self._wf('speed'), self._delay_span())
        return self._wf('frequency')

    def _apply_rate_input(self):
        """Only the field selected by Rate set by can be edited, the other one is computed"""
        by_speed = self._wf('rate_input') == INPUT_SPEED
        self.settings.child('waveform', 'speed').setOpts(readonly=not by_speed)
        self.settings.child('waveform', 'frequency').setOpts(readonly=by_speed)

    def _sync_rate_fields(self):
        """Write the value of the field that is computed (not the one that is typed)"""
        span = self._delay_span()
        self._syncing = True
        try:
            if self._wf('rate_input') == INPUT_SPEED:
                self.settings.child('waveform', 'frequency').setValue(frequency_from_speed(self._wf('speed'), span))
            else:
                self.settings.child('waveform', 'speed').setValue(speed_from_frequency(self._wf('frequency'), span))
        finally:
            self._syncing = False

    def _plan(self):
        """(n_points, rate, actual frequency) for the current rate setting"""
        return plan_table(self._requested_frequency(), self._servo_dt, min(TABLE_POINTS, self._max_wave_points))

    def _update_plan_info(self):
        """Show what the current settings give, without touching the hardware"""
        if self._servo_dt is None:
            return
        try:
            span = self._delay_span()
            low, high = self._position_range()
            self.settings.child('waveform', 'range').setValue(f'{low:.3f} - {high:.3f} um')
            self._sync_rate_fields()
            actual_frequency = self._plan()[2]
            self.settings.child('waveform', 'actual_frequency').setValue(actual_frequency)
            self.settings.child('waveform', 'actual_speed').setValue(speed_from_frequency(actual_frequency, span))
            self._set_waveform_status('Stopped' if not self._waveform_running else 'Running (settings changed: '
                                                                                   'press Start to apply)')
        except ValueError as exc:
            self._set_waveform_status(str(exc))

    def _check_range(self, low: float, high: float):
        """Refuse a waveform leaving the axis travel range (or the module bounds), before anything moves"""
        axis_min, axis_max = self.settings['axis_infos', 'min'], self.settings['axis_infos', 'max']
        if low < axis_min or high > axis_max:
            raise ValueError(f'The waveform ({low:.3f} - {high:.3f}) leaves the travel range of the axis '
                             f'({axis_min:.3f} - {axis_max:.3f})')
        if self.settings['bounds', 'is_bounds']:
            bound_min, bound_max = self.settings['bounds', 'min_bound'], self.settings['bounds', 'max_bound']
            if low < bound_min or high > bound_max:
                raise ValueError(f'The waveform ({low:.3f} - {high:.3f}) leaves the bounds of the module '
                                 f'({bound_min:.3f} - {bound_max:.3f})')

    # ---- waveform ---------------------------------------------------------------------------------------------
    def start_waveform(self):
        """Define the wave table from the settings, go to its starting position and start the wave generator"""
        if not self._has_wave_generator:
            raise RuntimeError('This controller has no wave generator')
        device, axis = self.controller.device, self.axis_name
        if not self.controller.get_servo(axis):
            raise RuntimeError('Switch on the closed loop first: the wave generator needs the servo')

        shape = self._wf('shape')
        span = self._delay_span()
        low, high = self._position_range()
        peak_to_peak = high - low
        self._check_range(low, high)
        n_points, rate, actual_frequency = self._plan()
        cycles = int(self._wf('cycles'))
        actual_speed = speed_from_frequency(actual_frequency, span)
        start_delay = position_to_delay(low, self._wf('time_zero'), self._increasing())

        self._stop_generator()
        device.WCL(WAVE_TABLE)
        if shape == SHAPE_SINE:
            device.WAV_SIN_P(table=WAVE_TABLE, firstpoint=0, numpoints=n_points, append='X',
                             center=n_points // 2, amplitude=peak_to_peak, offset=low, seglength=n_points)
        else:
            device.WAV_RAMP(table=WAVE_TABLE, firstpoint=0, numpoints=n_points, append='X',
                            center=n_points // 2,
                            speedupdown=corner_points(self._wf('corner_smoothing'), n_points),
                            amplitude=peak_to_peak, offset=low, seglength=n_points)
        self._check_table(device, n_points, low, high)

        device.WSL(WAVE_GENERATOR, WAVE_TABLE)
        device.WTR(0, rate, 1)  # table rate, linear interpolation between the points
        device.WGC(WAVE_GENERATOR, cycles)  # 0 = until stopped

        # like PI's own sample: go to the starting position of the waveform before starting it
        device.MOV(axis, low)
        pitools.waitontarget(device, axis, timeout=10)
        time.sleep(0.2)

        device.WGO(WAVE_GENERATOR, 1)
        self._waveform_running = True
        self.settings.child('waveform', 'running').setValue(True)
        self.settings.child('waveform', 'actual_frequency').setValue(actual_frequency)
        self.settings.child('waveform', 'actual_speed').setValue(actual_speed)
        self.settings.child('waveform', 'range').setValue(f'{low:.3f} - {high:.3f} um')
        self._set_waveform_status(
            f'Running: {shape.lower()}, delay {self._wf("delay_min"):g} to {self._wf("delay_max"):g} fs at '
            f'{actual_speed:.4g} fs/s ({actual_frequency:.4g} Hz), from {start_delay:g} fs, '
            f'{"until stopped" if cycles == 0 else f"{cycles} cycles"}')

    def _check_table(self, device, n_points: int, low: float, high: float):
        """Read the table back from the controller and check it stays within the requested range"""
        device.qGWD(WAVE_TABLE, 1, n_points)
        start = time.time()
        while device.bufstate is not True and time.time() - start < 10:
            time.sleep(0.01)
        table = np.array(device.bufdata, dtype=float).ravel()
        if len(table) == 0 or table.min() < low - RANGE_EPSILON or table.max() > high + RANGE_EPSILON:
            self._stop_generator()
            raise RuntimeError(f'The wave table defined in the controller ({table.min():.3f} - '
                               f'{table.max():.3f}) is not within the requested range ({low:.3f} - {high:.3f}): '
                               f'the waveform is not started')

    def _stop_generator(self):
        self.controller.device.WGO(WAVE_GENERATOR, 0)

    def stop_waveform(self, message: str = 'Stopped', emit_position: bool = True):
        """Stop the wave generator, the stage stays where it is"""
        if self.controller is not None and self._has_wave_generator:
            self._stop_generator()
        self._waveform_running = False
        self.settings.child('waveform', 'running').setValue(False)
        self._set_waveform_status(message)
        if emit_position and self.controller is not None:
            self.move_done()  # shows where the stage stopped

    def _stop_waveform_before_move(self):
        if self._waveform_running:
            self.stop_waveform('Stopped by a move command', emit_position=False)

    def _refresh_running_state(self):
        """Notice the end of a waveform with a finite number of cycles"""
        if self._waveform_running and not self.controller.device.IsGeneratorRunning(WAVE_GENERATOR)[WAVE_GENERATOR]:
            self._waveform_running = False
            self.settings.child('waveform', 'running').setValue(False)
            self._set_waveform_status('Finished')

    # ---- the standard actuator methods, aware of the waveform ----------------------------------------------------
    def get_actuator_value(self):
        position = super().get_actuator_value()
        self.settings.child('waveform', 'current_delay').setValue(
            round(position_to_delay(float(position.value()), self._wf('time_zero'), self._increasing()), 3))
        if self._waveform_running:
            self._refresh_running_state()
        return position

    def move_abs(self, position):
        self._stop_waveform_before_move()
        super().move_abs(position)

    def move_rel(self, position):
        self._stop_waveform_before_move()
        super().move_rel(position)

    def move_home(self, *args):
        self._stop_waveform_before_move()
        super().move_home(*args)

    def stop_motion(self, *args, **kwargs):
        if self._waveform_running:
            self._stop_generator()
            self._waveform_running = False
            self.settings.child('waveform', 'running').setValue(False)
            self._set_waveform_status('Stopped')
        try:
            super().stop_motion(*args, **kwargs)
        except GCSError as exc:
            # PI controllers answer a stop command (#24) with error 10 "stopped by command": expected, not a
            # failure. The standard plugin lets it through, which skips its move_done.
            if exc.val != gcserror.E10_PI_CNTR_STOP:
                raise
            self.move_done()

    def close(self):
        if self.controller is not None and self._waveform_running:
            try:
                self._stop_generator()
            except Exception:
                pass
            self._waveform_running = False
        super().close()


